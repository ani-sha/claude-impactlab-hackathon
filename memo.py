"""Claude drafts a one-page funder memo. Every figure is passed in from the engine; Claude does no math.
A person reviews the draft before it goes anywhere. Nothing is sent."""
import json
import os

import anthropic

MODEL = "claude-opus-5-5"
SYSTEM = (
    "You draft one-page funder memos for a small Orange County nonprofit that builds affordable for-sale homes. "
    "Use ONLY the numbers in the JSON you are given, copied exactly; never compute, round differently, or invent "
    "a number, program, statute, date or address. Keep each figure's label: if the JSON marks it ASSUMPTION or "
    "UNKNOWN, say so in the memo. Mention that programs marked funds_unconfirmed or unknown are not counted. "
    "Structure: headline ask, the project, the gap per home and why (cost vs family price set by statute), "
    "how much of the cost is time waiting on permits in this city, what is already lined up, what a gift pays for, "
    "and a short 'Sources and assumptions' list. Plain language, under 350 words. End with: "
    "'Draft generated by a prototype; not financial or legal advice. Reviewed by: ____'."
)


def available() -> bool:
    return bool(os.environ.get("ANTHROPIC_API_KEY") or os.environ.get("ANTHROPIC_AUTH_TOKEN"))


def draft_memo(facts: dict) -> str:
    client = anthropic.Anthropic()
    try:
        response = client.beta.messages.create(
            model=MODEL,
            max_tokens=16000,
            betas=["server-side-fallback-2026-07-01"],
            fallbacks="default",
            output_config={"effort": "medium"},
            system=SYSTEM,
            messages=[{"role": "user", "content": "Project facts (JSON):\n" + json.dumps(facts, indent=1)}],
        )
    except anthropic.AuthenticationError:
        return "Claude API key rejected. Check ANTHROPIC_API_KEY in your .env."
    except anthropic.RateLimitError:
        return "Claude API rate limit hit. Try again in a minute."
    except anthropic.APIStatusError as e:
        return f"Claude API error {e.status_code}."
    except anthropic.APIConnectionError:
        return "Could not reach the Claude API (network)."
    if response.stop_reason == "refusal":
        return "Claude declined to draft this memo."
    return "".join(b.text for b in response.content if b.type == "text")
